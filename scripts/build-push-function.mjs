import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const runtime=await readFile(new URL('supabase/functions/background-reminders/runtime.txt',root),'utf8');
const night=(await readFile(new URL('dist/js/tahajjud.js',root),'utf8')).replace(/^export /gm,'');
const shared=(await readFile(new URL('dist/js/reminder-events.js',root),'utf8')).replace(/^import .*\n/,'').replace(/^export /gm,'');
const core=(await readFile(new URL('supabase/functions/background-reminders/core.mjs',root),'utf8')).replace(/^import .*\n/gm,'').replace(/^export /gm,'');
const tyumen=(await readFile(new URL('dist/js/tyumen-source.js',root),'utf8')).replace(/^export /gm,'');
const asr=(await readFile(new URL('dist/js/asr-first.js',root),'utf8')).replace(/^export /gm,'');
const [imports,adapter]=runtime.split("const sql=",2);
const output='// Generated by scripts/build-push-function.mjs; edit core.mjs and runtime.txt.\n'+imports+'\n'+tyumen+'\n'+asr+'\n'+night+'\n'+shared+'\n'+core+'\nconst sql='+adapter;
const target=new URL('supabase/functions/background-reminders/index.ts',root);
if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==output)throw Error('Push function bundle is stale');}
else await writeFile(target,output);
console.log('PASS: background reminder function includes the exact shared scheduler.');
