import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
// Build the same self-contained module on Windows and Linux.
const readText=async path=>(await readFile(new URL(path,root),'utf8')).replace(/\r\n/g,'\n');
const runtime=await readText('supabase/functions/background-reminders/runtime.txt');
const dhikr=(await readText('dist/js/dhikr-reminder.js')).replace(/^export /gm,'');
const night=(await readText('dist/js/tahajjud.js')).replace(/^export /gm,'');
const shared=(await readText('dist/js/reminder-events.js')).replace(/^import[^\r\n]*(?:\n|$)/gm,'').replace(/^export /gm,'');
const core=(await readText('supabase/functions/background-reminders/core.mjs')).replace(/^import[^\r\n]*(?:\n|$)/gm,'').replace(/^export /gm,'');
const tyumen=(await readText('dist/js/tyumen-source.js')).replace(/^export /gm,'');
const asr=(await readText('dist/js/asr-first.js')).replace(/^export /gm,'');
const competition=(await readText('supabase/functions/background-reminders/competition-push.mjs')).replace(/^export /gm,'');
const support=(await readText('supabase/functions/background-reminders/support-push.mjs')).replace(/^export /gm,'');
const firebase=(await readText('supabase/functions/background-reminders/firebase-support-sender.mjs')).replace(/^export /gm,'');
const nativeSupport=(await readText('supabase/functions/background-reminders/native-support-dispatch.mjs')).replace(/^export /gm,'');
const [imports,adapter]=runtime.split("const sql=",2);
const output='// Generated by scripts/build-push-function.mjs; edit core.mjs and runtime.txt.\n'+imports+'\n'+tyumen+'\n'+asr+'\n'+night+'\n'+dhikr+'\n'+shared+'\n'+competition+'\n'+support+'\n'+firebase+'\n'+nativeSupport+'\n'+core+'\nconst sql='+adapter;
const target=new URL('supabase/functions/background-reminders/index.ts',root);
if(process.argv.includes('--check')){if((await readFile(target,'utf8')).replace(/\r\n/g,'\n')!==output)throw Error('Push function bundle is stale');}
else await writeFile(target,output);
console.log('PASS: background reminder function includes the exact shared scheduler.');
