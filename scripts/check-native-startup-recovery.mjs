import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const source=await readFile(new URL('../mobile/native/native-startup-recovery.js',import.meta.url),'utf8');
const recover=vm.runInNewContext('('+source+')',{URL});
const context={origin:'https://localhost',versionCode:445,webVersion:445};
const saved=new Map([['account','existing-session'],['reading-page','25'],['downloads','existing-offline-quran']]);
let reloads=0,unregisters=0;
const env={location:{origin:context.origin,href:'https://localhost/#quran?view=mushaf&page=25',replace(url){assert.equal(url,this.href);reloads++;}},localStorage:saved,navigator:{serviceWorker:{controller:{oldVersion:338},getRegistrations:async()=>[{scope:'https://localhost/',unregister:async()=>{unregisters++;return true;}}]}}};
const before=JSON.stringify([...saved]);
assert.equal(await recover(context,env),true);assert.equal(reloads,1);assert.equal(unregisters,1);assert.equal(JSON.stringify([...saved]),before);
assert.deepEqual({...env.__SALAH_NATIVE_BOOT__},{versionCode:445,webVersion:445});
assert.ok(Object.isFrozen(env.__SALAH_NATIVE_BOOT__));
env.navigator.serviceWorker={controller:null,getRegistrations:async()=>[]};
assert.equal(await recover(context,env),false);assert.equal(reloads,1,'A clean launch is never reloaded');
env.navigator.serviceWorker={controller:{},getRegistrations:async()=>[{scope:'https://localhost/',unregister:async()=>false}]};
assert.equal(await recover(context,env),false);assert.equal(reloads,1,'A failed cleanup must not trigger a reload loop');
env.navigator.serviceWorker={controller:null,getRegistrations:async()=>[{scope:'https://other.test/',unregister:async()=>{throw Error('foreign worker touched');}}]};
assert.equal(await recover(context,env),false);
env.location.origin='https://other.test';delete env.__SALAH_NATIVE_BOOT__;
assert.equal(await recover(context,env),false);assert.equal(env.__SALAH_NATIVE_BOOT__,undefined);assert.equal(reloads,1);
const activity=await readFile(new URL('../mobile/native/android/MainActivity.java',import.meta.url),'utf8');
const listener=await readFile(new URL('../mobile/native/android/SalahNativeStartup.java',import.meta.url),'utf8');
assert.ok(activity.indexOf('bridgeBuilder.addWebViewListener')<activity.indexOf('super.onCreate'));
assert.ok(listener.includes('if(checked)return;'));assert.ok(listener.includes('checked=true;'));
assert.ok(activity.includes('updates.rejectTrial()'),'Broken bundle rollback stays enabled');
console.log('PASS: legacy worker recovery preserves route, account and offline data; clean, failed, foreign and repeated native launches cannot loop.');
