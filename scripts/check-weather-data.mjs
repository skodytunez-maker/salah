import assert from 'node:assert/strict';
const store=new Map();
globalThis.localStorage={getItem:key=>store.get(key)??null,setItem:(key,value)=>store.set(key,value)};
const {settings,updateSettings}=await import('../dist/js/storage.js');
const {weatherFrame,weatherKey,loadWeather}=await import('../dist/js/weather-data.js');
const realNow=Date.now;
let now=Date.parse('2026-10-03T10:00:00Z'),requests=0;
Date.now=()=>now;
const city={name:'Тюмень',latitude:57.15222,longitude:65.52722,timezone:'Asia/Yekaterinburg'};
updateSettings({weather:true,city});
const sample={temperature_2m:8,apparent_temperature:6,weather_code:61,cloud_cover:95,precipitation:0,wind_speed_10m:3,interval:900,dataAt:now,fetchedAt:now};
assert.equal(weatherFrame(sample,now).kind,'rain');
assert.ok(weatherFrame(sample,now).precipitation>=.2,'a rain condition remains visible even when a tiny interval sum is rounded to zero');
assert.ok(weatherFrame({...sample,weather_code:51,precipitation:.01},now).precipitation>=.2,'drizzle must not disappear');
assert.equal(weatherFrame({...sample,weather_code:3,precipitation:0},now).precipitation,0,'overcast skies must not invent rain');
assert.ok(weatherFrame({...sample,precipitation:2},now).precipitation>weatherFrame(sample,now).precipitation,'heavy rain is visually stronger');
assert.equal(weatherFrame(sample,now+121*60000).fresh,false,'stale weather must not be presented as current');
store.set('salah:'+weatherKey(city),JSON.stringify({...sample,weather_code:3,locationKey:weatherKey(city)}));
globalThis.fetch=async (url,options)=>{
 requests++;
 assert.equal(new URL(url).searchParams.get('latitude'),String(city.latitude));
 assert.equal(options.cache,'no-store');
 return {ok:true,json:async()=>({utc_offset_seconds:0,current:{...sample,weather_code:61,time:new Date(now).toISOString().slice(0,16)}})};
};
now+=9*60000;
assert.equal((await loadWeather(city)).weather_code,3);
assert.equal(requests,0,'a recent cached result avoids redundant requests');
now+=2*60000;
const [rain,shared]=await Promise.all([loadWeather(city),loadWeather(city)]);
assert.equal(requests,1,'after ten minutes a changed rain condition is fetched; simultaneous callers share one request');
assert.equal(rain.weather_code,61);
assert.deepEqual(shared,rain);
updateSettings({weather:false});
assert.equal(await loadWeather(city),null);
assert.equal(requests,1,'disabling weather stops network requests');
Date.now=realNow;
console.log('PASS: visible light/rounded rain, stronger heavy rain, no invented rain, stale data, cache renewal, request deduplication and disabled weather.');
