import assert from 'node:assert/strict';
import {Window} from '../tests/staff/node_modules/happy-dom/lib/index.js';
import {chatDeviceLanguage,mountChatTranslation} from '../dist/js/chat-translation.js';
const win=new Window({url:'https://fixture.invalid/#support'}),doc=win.document;
assert.equal(chatDeviceLanguage({language:'ru-RU',languages:['en-US']}),'ru');
assert.equal(chatDeviceLanguage({language:'zh-TW'}),'zh-Hant');
assert.equal(chatDeviceLanguage({language:'invalid$$',languages:['ar-SA']}),'ar');
assert.equal(chatDeviceLanguage({}),null);
Object.defineProperty(win.navigator,'language',{configurable:true,value:'ru-RU'});
doc.body.innerHTML='<header></header><main></main>';
const log=doc.querySelector('main'),toolbar=doc.querySelector('header');
assert.equal(mountChatTranslation(log,toolbar,{actorId:'owner'}),null,'Unavailable engines do not add controls or activate downloads');
let answer,detected=[],used=[],creates=0;
win.LanguageDetector={availability:async()=> 'available',create:async()=>({
 async detect(text){detected.push(text);return [{detectedLanguage:text.startsWith('Русский')?'ru':'en',confidence:.99}];},destroy(){}
})};
win.Translator={availability:async()=> 'available',create:async({sourceLanguage,targetLanguage})=>{
 creates++;assert.equal(sourceLanguage,'en');assert.equal(targetLanguage,'ru');
 return {translate:async text=>{used.push(text);return text==='Wait for translation' ? new Promise(done=>{answer=done;}) : '<b>Перевод</b>';},destroy(){}};
}};
const msg=(id,body,author_id='guest',redacted=false)=>({id,body,author_id,redacted});
const messages=[msg('one','English message'),msg('mine','Own message','owner'),msg('removed','Removed message','guest',true),msg('same','Русский текст')];
function paint(rows){log.innerHTML=rows.map(({id})=>'<article data-message="'+id+'"><div class="staff-bubble"><p>Оригинал</p></div></article>').join('');}
const flush=async()=>{for(let i=0;i<4;i++)await new Promise(r=>setImmediate(r));};
paint(messages);
const translation=mountChatTranslation(log,toolbar,{actorId:'owner'});
translation.sync(messages);await flush();assert.deepEqual(detected,[]);
const auto=toolbar.querySelector('button');auto.click();await flush();
assert.deepEqual(detected,['Русский текст','English message']);
assert.deepEqual(used,['English message']);assert.equal(creates,1);
const row=log.querySelector('[data-message=one]'),translated=row.querySelector('p[data-chat-translation-attachment]'),original=row.querySelector('p[data-chat-translation-original]');
assert.equal(translated.textContent,'<b>Перевод</b>');assert.equal(translated.querySelector('b'),null);assert.equal(translated.lang,'ru');
assert.equal(original.hidden,true);
row.querySelector('button').click();assert.equal(original.hidden,false);assert.equal(translated.hidden,true);
paint([...messages,msg('new-one','New incoming text')]);translation.sync([...messages,msg('new-one','New incoming text')]);await flush();
assert.equal(used.filter(text=>text==='English message').length,1,'A chat refresh only translates new content');
assert.equal(log.querySelector('[data-message=one] p[data-chat-translation-original]').hidden,false,'The original choice survives a refresh and new messages');
const secondToolbar=doc.createElement('header');doc.body.append(secondToolbar);
const secondRoom=mountChatTranslation(log,secondToolbar,{actorId:'other'});
assert.equal(secondToolbar.querySelector('button').getAttribute('aria-pressed'),'false','The opt-in is scoped to the current account');
secondRoom.dispose();
paint([msg('old','Wait for translation')]);translation.sync([msg('old','Wait for translation')]);await flush();assert.equal(typeof answer,'function');
paint([msg('next','Русский текст')]);translation.sync([msg('next','Русский текст')]);answer('Перевод старого чата');await flush();
assert.doesNotMatch(log.textContent,/старого чата/);
paint([msg('one','English message')]);translation.sync([msg('one','English message')],'different-room');await flush();
assert.equal(used.filter(text=>text==='English message').length,2,'Changing rooms clears previous source, translation and display preference');
auto.click();translation.dispose();assert.equal(toolbar.querySelector('button'),null);
win.Translator.availability=async()=> 'downloadable';
const toTranslate=[msg('first','First English sentence'),msg('second','Second English sentence')];
paint(toTranslate);
const downloading=mountChatTranslation(log,toolbar,{actorId:'owner'});
downloading.sync(toTranslate);toolbar.querySelector('button').click();await flush();
const prompts=log.querySelectorAll('button[data-chat-translation-attachment]');
assert.equal(prompts.length,2);
prompts[0].click();await flush();
assert.equal(log.querySelectorAll('p[data-chat-translation-attachment]').length,2,'One activation installs the pair for both messages');
downloading.dispose();
await win.happyDOM.close();
console.log('PASS: phone locale priority, opt-in, incoming text only, same language, plain text, original toggle, stale result isolation and fail-closed native capability.');
