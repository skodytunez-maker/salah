import assert from 'node:assert/strict';
import{createLessonRoute}from '../dist/js/lesson-route.js';
const tick=()=>new Promise(resolve=>setImmediate(resolve));
const host=()=>({isConnected:true,innerHTML:'',retry:{onclick:null},querySelector(selector){assert.equal(selector,'[data-retry-lesson]');return this.retry;}});
let loads=0,resolveLoad,shown=[],stops=0,busy=false;
const route=createLessonRoute({load:()=>{loads++;return new Promise(resolve=>resolveLoad=resolve);}});
assert.equal(loads,0,'Ordinary startup must not import the private lesson graph');
const first=host(),hash='#lesson?view=teacher';
route.showLessonInvitation(first,{hash});route.showLessonInvitation(first,{hash});
await tick();assert.equal(loads,1);assert.match(first.innerHTML,/Открываем кабинет/);
route.stopStudentLesson();first.isConnected=false;
const module={showLessonInvitation:(root,options)=>shown.push([root,options.hash]),stopStudentLesson:()=>stops++,studentLessonBusy:()=>busy};
resolveLoad(module);await tick();assert.equal(shown.length,0,'Leaving during import must not reopen a stale cabinet');
const second=host();route.showLessonInvitation(second,{hash:'#lesson'});assert.deepEqual(shown,[[second,'#lesson']]);assert.equal(loads,1);
busy=true;assert.equal(route.studentLessonBusy(),true);route.stopStudentLesson();assert.equal(stops,1);
let attempts=0;const retryHost=host(),retryRoute=createLessonRoute({load:()=>{attempts++;return attempts===1?Promise.reject(Error('offline')):Promise.resolve(module);}});
retryRoute.showLessonInvitation(retryHost,{hash:'#lesson'});await tick();assert.match(retryHost.innerHTML,/Не удалось открыть кабинет/);
assert.equal(typeof retryHost.retry.onclick,'function');retryHost.retry.onclick();await tick();assert.equal(attempts,2);assert.equal(shown.at(-1)[0],retryHost);
let finish;const changed=host(),changedRoute=createLessonRoute({load:()=>new Promise(resolve=>finish=resolve)});
changedRoute.showLessonInvitation(changed,{hash:'#lesson?tab=overview'});await tick();
changedRoute.showLessonInvitation(changed,{hash:'#lesson?tab=homework'});finish(module);await tick();
assert.equal(shown.at(-1)[1],'#lesson?tab=homework','Only the latest requested cabinet view may render');
console.log('PASS: private lessons load only on entry; one import, cancellation, latest route, busy-state forwarding and network retry preserve the ordinary app.');
